HEADER = """<!-- Generated by scripts/gen_tools_doc.py; do not edit manually. -->

# Tool Reference

`gdb-mcp` exposes {tool_count} explicit tools for GDB workflows. Every tool
that operates on a session requires an explicit `session_id`; there is no
implicit current session.

Safety levels:

- `Read`: reads debugger or target state (`readOnlyHint=true`).
- `Mutation`: changes debugger state such as breakpoints, selected frames, or paths.
- `Execution`: starts, resumes, interrupts, attaches, detaches, or kills a target.
- `Unsafe`: requires `--unsafe` or `GDB_MCP_ALLOW_UNSAFE=1`.

Tool discovery profiles:

- `full` is the compatible default and publishes all {tool_count} tools.
- `core` publishes the {core_count}-tool common local-debugging surface.
- `advanced:<group>[,<group>]` publishes `core` plus selected `binary_analysis`,
  `reverse_debugging`, `remote_target`, `diagnostics`, or `unsafe` groups.
- Combine with `--tools` / `--exclude-tools` (or `GDB_MCP_TOOLS` /
  `GDB_MCP_EXCLUDE_TOOLS`); `exclude` takes precedence.
"""


def _safety_label(tool: dict[str, Any], unsafe_tools: set[str]) -> str:
    if tool["name"] in unsafe_tools:
        return "Unsafe"
    ann = tool.get("annotations") or {}
    if ann.get("readOnlyHint") is True:
        return "Read"
    if ann.get("destructiveHint") is True:
        return "Execution"
    return "Mutation"


def _profile_label(name: str, core_set: set[str]) -> str:
    if name in core_set:
        return "`core`"
    groups = [
        f"`advanced:{group}`"
        for group, meta in ADVANCED_TOOL_GROUPS.items()
        if name in meta["tools"]
    ]
    return ", ".join(groups) if groups else "`full`"


def _format_params(tool: dict[str, Any]) -> str:
    schema = tool.get("inputSchema") or {}
    props = schema.get("properties") or {}
    if not props:
        return "none"
    required = set(schema.get("required") or [])
    items = [
        f"`{key}`*" if key in required else f"`{key}`"
        for key in props
        if key != "context"
    ]
    return ", ".join(items) if items else "none"


def _purpose_line(description: str) -> str:
    first_line = " ".join(description.strip().splitlines()).strip()
    if not first_line:
        return ""
    if ". " in first_line:
        first_line = first_line.split(". ", 1)[0].rstrip(".") + "."
    return first_line.replace("|", "\\|")


async def render_tools_markdown() -> str:
    raw_tools = await mcp.list_tools()
    by_name: dict[str, dict[str, Any]] = {
        tool.name: tool.model_dump(mode="json", by_alias=True, exclude_none=True)
        for tool in raw_tools
    }
    mapped_names = [name for _, names in SECTIONS for name in names]
    if len(mapped_names) != len(set(mapped_names)):
        raise ValueError("Duplicate tool name in SECTIONS mapping")
    missing_from_sections = sorted(set(by_name) - set(mapped_names))
    extra_in_sections = sorted(set(mapped_names) - set(by_name))
    if missing_from_sections or extra_in_sections:
        raise ValueError(
            f"Section mapping drift: missing={missing_from_sections}, extra={extra_in_sections}"
        )

    core_set = set(CORE_TOOL_PROFILE)
    unsafe_tools = set(ADVANCED_TOOL_GROUPS["unsafe"]["tools"])

    parts = [
        HEADER.format(
            tool_count=len(by_name),
            core_count=len(core_set),
        ).rstrip()
    ]
    for section_title, tool_names in SECTIONS:
        parts.append("")
        parts.append(f"## {section_title}")
        parts.append("")
        parts.append("| Tool | Safety | Profile | Parameters | Purpose |")
        parts.append("| --- | --- | --- | --- | --- |")
        for name in tool_names:
            tool = by_name[name]
            safety = _safety_label(tool, unsafe_tools)
            profile = _profile_label(name, core_set)
            params = _format_params(tool)
            purpose = _purpose_line(tool.get("description", ""))
            parts.append(f"| `{name}` | {safety} | {profile} | {params} | {purpose} |")
    parts.append("")
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--write", action="store_true", help="Write generated file")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if existing file differs from generated output",
    )
    args = parser.parse_args()

    rendered = asyncio.run(render_tools_markdown())
    if args.check:
        if not args.output.exists():
            print(f"error: {args.output} does not exist", file=sys.stderr)
            return 1
        existing = args.output.read_text(encoding="utf-8")
        if existing != rendered:
            diff = "".join(
                difflib.unified_diff(
                    existing.splitlines(keepends=True),
                    rendered.splitlines(keepends=True),
                    fromfile=str(args.output),
                    tofile="generated",
                )
            )
            print(diff, file=sys.stderr)
            print(
                "error: docs/TOOLS.md is out of date; run: "
                "uv run python scripts/gen_tools_doc.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"{args.output} is up to date.")
        return 0

    if args.write:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
        print(f"Wrote {args.output}")
        return 0

    print(rendered, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
